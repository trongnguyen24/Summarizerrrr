import { readFile, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import { scanIconNames } from './scanIconNames.mjs'

const API = 'https://api.iconify.design'
const LOG = '[icons]'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const SRC_DIR = path.join(ROOT, 'src')
const BUNDLE_PATH = path.join(ROOT, 'src/lib/icons/iconBundle.js')

const HEADER = `// AUTO-GENERATED by build/icons/iconBundlePlugin.mjs — do not edit by hand.
// Kept in sync automatically on \`npm run dev\` / \`npm run build\`, or via \`npm run icons:sync\`.
//
// Bundling the icon data is what makes <Icon /> render synchronously on the very
// first frame. @iconify/svelte's default component renders nothing at all until
// its fetch resolves, which is what used to make the side panel's icons pop in
// and shift the layout on every open.
`

function prefixOf(name) {
  return name.slice(0, name.indexOf(':'))
}

function localOf(name) {
  return name.slice(name.indexOf(':') + 1)
}

function groupByPrefix(names) {
  const grouped = new Map()
  for (const name of names) {
    const prefix = prefixOf(name)
    if (!grouped.has(prefix)) grouped.set(prefix, [])
    grouped.get(prefix).push(localOf(name))
  }
  return grouped
}

/**
 * Reduce a collection to exactly the icons asked for, following alias chains so
 * a kept alias always keeps its parent. Applied to fetched and cached data
 * alike so both paths produce byte-identical output.
 */
function subsetCollection(collection, wantedLocals) {
  const icons = {}
  const aliases = {}
  const pending = [...wantedLocals]
  const seen = new Set()

  while (pending.length > 0) {
    const name = pending.pop()
    if (seen.has(name)) continue
    seen.add(name)

    if (collection.icons?.[name]) {
      icons[name] = collection.icons[name]
    } else if (collection.aliases?.[name]) {
      aliases[name] = collection.aliases[name]
      if (collection.aliases[name].parent) pending.push(collection.aliases[name].parent)
    }
  }

  const subset = { prefix: collection.prefix, icons: sortKeys(icons) }
  if (Object.keys(aliases).length > 0) subset.aliases = sortKeys(aliases)
  // Collection-level defaults; generateIcon() needs them to compute the viewBox.
  if (collection.width != null) subset.width = collection.width
  if (collection.height != null) subset.height = collection.height
  return subset
}

function sortKeys(object) {
  return Object.fromEntries(Object.entries(object).sort(([a], [b]) => a.localeCompare(b)))
}

async function fetchCollection(prefix, locals) {
  const url = `${API}/${prefix}.json?icons=${locals.join(',')}`
  const response = await fetch(url)
  if (!response.ok) {
    throw new Error(`${prefix}: HTTP ${response.status} from ${API}`)
  }

  const json = await response.json()
  if (json.not_found?.length) {
    throw new Error(
      `These icon names do not exist in the "${prefix}" collection:\n` +
        json.not_found.map((n) => `  ${prefix}:${n}`).join('\n') +
        `\n\nFix the typo at the call site — an unknown name renders nothing at all at runtime.`
    )
  }

  return subsetCollection(json, locals)
}

async function readExistingBundle() {
  try {
    await readFile(BUNDLE_PATH, 'utf8')
  } catch {
    return { names: [], collections: [] }
  }
  const module = await import(`${pathToFileURL(BUNDLE_PATH).href}?t=${Date.now()}`)
  return {
    names: module.iconNames ?? [],
    collections: module.iconCollections ?? [],
  }
}

function serialize(names, collections) {
  const namesBlock = names.map((name) => `  ${JSON.stringify(name)},`).join('\n')
  const collectionsBlock = collections
    .map((collection) => JSON.stringify(collection, null, 2).replace(/^/gm, '  '))
    .join(',\n')

  return `${HEADER}
export const iconNames = [
${namesBlock}
]

export const iconCollections = [
${collectionsBlock},
]
`
}

/**
 * Bring src/lib/icons/iconBundle.js in line with the icons `src/` actually uses.
 *
 * The bundle is its own cache: when the set of names is unchanged this touches
 * neither the network nor the disk, which is the case for every ordinary build.
 */
export async function syncIconBundle({ silent = false } = {}) {
  const log = silent ? () => {} : (message) => console.log(`${LOG} ${message}`)

  const wanted = await scanIconNames(SRC_DIR)
  const existing = await readExistingBundle()

  const wantedSet = new Set(wanted)
  const haveSet = new Set(existing.names)
  const added = wanted.filter((name) => !haveSet.has(name))
  const removed = existing.names.filter((name) => !wantedSet.has(name))

  if (added.length === 0 && removed.length === 0) {
    log(`${wanted.length} icons, no changes`)
    return { changed: false, added, removed, total: wanted.length }
  }

  const grouped = groupByPrefix(wanted)
  let collections

  if (added.length === 0) {
    // Pure removal — everything still needed is already on disk, so prune offline.
    const byPrefix = new Map(existing.collections.map((c) => [c.prefix, c]))
    collections = [...grouped]
      .filter(([prefix]) => byPrefix.has(prefix))
      .map(([prefix, locals]) => subsetCollection(byPrefix.get(prefix), locals))
  } else {
    // Refetch every prefix rather than merging: it is the only way to keep alias
    // chains and collection-level defaults coherent, and it only runs on change.
    log(`fetching ${added.length} new icon(s): ${added.join(', ')}`)
    try {
      collections = await Promise.all(
        [...grouped].map(([prefix, locals]) => fetchCollection(prefix, locals))
      )
    } catch (error) {
      throw new Error(
        `${LOG} could not update the icon bundle.\n\n${error.message}\n\n` +
          `Missing: ${added.join(', ')}\n` +
          `Run \`npm run icons:sync\` while online to fix.`
      )
    }
  }

  collections.sort((a, b) => a.prefix.localeCompare(b.prefix))
  const output = serialize(wanted, collections)

  await mkdir(path.dirname(BUNDLE_PATH), { recursive: true })
  await writeFile(BUNDLE_PATH, output, 'utf8')

  const kb = Math.round(Buffer.byteLength(output) / 1024)
  log(
    `${wanted.length} icons across ${collections.length} collections (~${kb} KB)` +
      `${added.length ? `, +${added.length}` : ''}${removed.length ? `, -${removed.length}` : ''}`
  )
  if (removed.length > 0) log(`pruned: ${removed.join(', ')}`)

  return { changed: true, added, removed, total: wanted.length }
}

/**
 * Vite plugin wrapper.
 *
 * WXT calls `vite()` once per build target (background, content scripts, each
 * HTML page), each time constructing a fresh plugin object — so the memo has to
 * live at module scope, not in the factory closure, or the sync runs a dozen
 * times per build.
 */
let pending = null

export function iconBundlePlugin() {
  return {
    name: 'summarizerrrr:icon-bundle',
    buildStart() {
      pending ??= syncIconBundle()
      return pending
    },
  }
}

const invokedDirectly =
  process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href

if (invokedDirectly) {
  syncIconBundle().catch((error) => {
    console.error(error.message)
    process.exit(1)
  })
}
